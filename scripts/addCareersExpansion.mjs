// Merge top-ups into ADDITIONS so we can run a single pass.
for (const [k, v] of Object.entries(TOP_UP)) {
  ADDITIONS[k] = [...(ADDITIONS[k] ?? []), ...v];
}

let totalAdded = 0;

for (const [streamKey, additions] of Object.entries(ADDITIONS)) {
  const filePath = path.join(STREAM_DIR, `${streamKey}.js`);
  const original = fs.readFileSync(filePath, "utf8");

  // Extract existing titles so we don't duplicate.
  const existingTitles = new Set();
  const titleMatches = original.matchAll(/title:\s*"([^"]+)"/g);
  for (const m of titleMatches) existingTitles.add(m[1]);

  const toAdd = additions.filter(([title]) => !existingTitles.has(title));
  if (toAdd.length === 0) {
    console.log(`  ${streamKey.padEnd(15)}: 0 new (all already present)`);
    continue;
  }

  // Find the closing `];` at the end of the CAREERS array.  Entries are always
  // the last array literal in the file (just before the trailing newline).
  // We insert new entries right before the closing bracket.
  const newBlock = toAdd
    .map(([title, code]) => `  { title: "${title}", ofoCode: "${code}" },`)
    .join("\n");

  // Strategy: find LAST occurrence of "\n];" inside the file — that ends CAREERS.
  const lastCloseIdx = original.lastIndexOf("\n];");
  if (lastCloseIdx === -1) {
    throw new Error(`Could not find CAREERS array closing in ${filePath}`);
  }

  const before = original.slice(0, lastCloseIdx + 1); // include the newline
  const after = original.slice(lastCloseIdx + 1); // starts with `];`
  const updated = `${before}${newBlock}\n${after}`;

  fs.writeFileSync(filePath, updated, "utf8");
  console.log(`  ${streamKey.padEnd(15)}: added ${toAdd.length} careers`);
  totalAdded += toAdd.length;
}

