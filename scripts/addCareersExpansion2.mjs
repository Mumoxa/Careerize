for (const [streamKey, additions] of Object.entries(ADDITIONS)) {
  const filePath = path.join(STREAM_DIR, `${streamKey}.js`);
  const original = fs.readFileSync(filePath, "utf8");

  const existingTitles = new Set();
  for (const m of original.matchAll(/title:\s*"([^"]+)"/g)) existingTitles.add(m[1]);

  const toAdd = additions.filter(([title]) => !existingTitles.has(title));
  totalSkipped += additions.length - toAdd.length;

  if (toAdd.length === 0) {
    console.log(`  ${streamKey.padEnd(15)}: 0 new (all present)`);
    continue;
  }

  const newBlock = toAdd
    .map(([title, code]) => `  { title: "${title}", ofoCode: "${code}" },`)
    .join("\n");

  const lastCloseIdx = original.lastIndexOf("\n];");
  if (lastCloseIdx === -1) throw new Error(`Could not find CAREERS array closing in ${filePath}`);

  const before = original.slice(0, lastCloseIdx + 1);
  const after = original.slice(lastCloseIdx + 1);
  fs.writeFileSync(filePath, `${before}${newBlock}\n${after}`, "utf8");
  console.log(`  ${streamKey.padEnd(15)}: added ${toAdd.length.toString().padStart(3)} careers`);
  totalAdded += toAdd.length;
}

